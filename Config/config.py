    # ================================================================
    # ПАРАМЕТРЫ СИГНАЛА
    # ================================================================
    
    TARGET_SR = 256          # целевая частота дискретизации (Гц)
    EPOCH_SEC = 2            # длительность эпохи (сек) — из датасета
    WINDOW_SEC = 4           # длительность окна для модели (сек)
    WINDOW_SIZE = TARGET_SR * WINDOW_SEC  # 1024 точки
    N_WINDOWS = 27           # количество окон для покрытия 30 секунд
    STRIDE = TARGET_SR * 1   # шаг между окнами (1 сек = 256 точек)
    
    # ================================================================
    # КАНАЛЫ (система 10-20)
