    HIGHCUT = 30.0    # верхняя граница (для неонатальных данных)
    NOTCH = 50.0      # частота сетевой наводки (Гц)
    
    # ================================================================
    # ВЕСА ПАТТЕРНОВ (из R-анализа)
    # ================================================================
    
    # Паттерн: вес в loss-функции
    # 000 — фон (уменьшаем, чтобы не перевешивал)
    # 111 — эталон приступа (полный вес)
    # остальные — спорные (средний вес)
    
    PATTERN_WEIGHTS = {
        # Полное согласие (золотой стандарт)
        '111': 1.0,      # 296 эпох, 32 пациента
    
        # Два эксперта согласны (высокая достоверность)
        '110': 0.9,      # 200 эпох, 2 пациента (A+B)
        '011': 0.85,     # 22 эпохи, 3 пациента (B+C)
        '101': 0.85,     # 1 эпоха, 3 пациента (A+C) - очень редкий
    
        # Один эксперт (спорные случаи)
        '010': 0.5,      # 428 эпох, 1 пациент (только B)
        '001': 0.4,      # 158 эпох, 8 пациентов (только C) - есть пациент с отрицательной каппа!
        '100': 0.3,      # 14 эпох, 0 пациентов (только A) - очень редкий
    
        # Фон (уверенное отсутствие)
        '000': 0.2,      # 6,590 эпох, 30 пациентов
    }
    
    # ================================================================
    # SEED CONTROL (Для воспроизводимости)
    # ================================================================
    
    SEED = 42
    
    @staticmethod
    def set_seed():
        """Фиксация всех генераторов случайных чисел"""
        random.seed(Config.SEED)
        np.random.seed(Config.SEED)
        torch.manual_seed(Config.SEED)
        torch.cuda.manual_seed_all(Config.SEED)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
        os.environ['PYTHONHASHSEED'] = str(Config.SEED)
    
    # ================================================================
